test('номера игр закреплены за рейтингом и продолжаются после перезапуска', async t => {
  const server = await startServer(t, SECRET, undefined, undefined, false);
  const admin = await signIn(server.http, SECRET);
  assert.equal((await admin('/games', 'POST', { title: 'Отдельная игра' })).status, 404);
  const rating = await body(await admin('/ratings', 'POST', { title: 'Ноябрь' }), 201);
  const another = await body(await admin('/ratings', 'POST', { title: 'Декабрь' }), 201);
  assert.deepEqual(new Set((await body(await admin('/ratings'))).map(entry => entry.id)), new Set([rating.id, another.id]));
  assert.equal((await fetch(server.http + '/api/ratings')).status, 401);
  const path = '/ratings/' + rating.id;
  const create = async (route = path) => body(await admin(route + '/games', 'POST', {}), 201);
  const games = await Promise.all([create(), create(), create()]);
  games.sort((a, b) => a.number - b.number);
  assert.deepEqual(games.map(game => game.title), ['Игра 1', 'Игра 2', 'Игра 3']);
  assert.deepEqual(games.map(game => game.ratingId), [rating.id, rating.id, rating.id]);
  assert.equal((await create('/ratings/' + another.id)).number, 1);
  assert.equal((await fetch(server.http + '/api' + path)).status, 401);
  assert.equal((await admin('/ratings/' + 'a'.repeat(32) + '/games', 'POST', {})).status, 404);
  const second = games[1];
  const secondPath = '/games/' + second.id;
  const details = await body(await admin(secondPath));
  assert.deepEqual(details.seats, []);
  assert.equal(details.links.panel, undefined);
  assert.equal(await connect(t, server.url('', 'host', SECRET, second.id)), 4403);
  const oldLink = await fetch(server.http + secondPath + '/panel').then(response => response.text());
  assert.match(oldLink, /assets\/platform\.js/);
  assert.equal(oldLink.includes(details.links.judge), false);
  assert.equal((await fetch(server.http + '/api' + secondPath)).status, 401);
  assert.equal(details.links.overlay, undefined);
  assert.equal(await connect(t, server.url('a'.repeat(32), 'screen', undefined, second.id)), 4403);
  assert.equal((await fetch(server.http + secondPath + '/hud')).status, 404);
  assert.equal((await fetch(server.http + '/watch' + secondPath)).status, 404);
  assert.equal((await admin(secondPath, 'PATCH', { published: true })).status, 400);
  await seedSeating(t, server, details);
  const player = await judge(t, server, details);
  assert.equal(latest(player, 'state').game, 2);
  cmd(player, 'winner', { v: 'red' });
  assert.ok(await until(() => latest(player, 'state').winner === 'red'));
  const list = await body(await admin(path));
  assert.deepEqual(list.games.map(game => game.number), [3, 2, 1]);
  assert.equal(list.games[1].winner, 'red');
  assert.equal(list.games[1].seats[0].total, 1);
  assert.equal(list.games[1].judge, details.links.judge);
  await server.stop();
  const restored = await startServer(t, SECRET, server.data, undefined, false);
  const next = await signIn(restored.http, SECRET);
  assert.equal((await body(await next(path + '/games', 'POST', {}), 201)).number, 4);
  assert.equal((await body(await next(secondPath))).number, 2);
});

