const assert = require('node:assert/strict');
const { test } = require('node:test');
const { startServer, signIn, testTournament, stageGames, placeTestGame, seedSeating, connect, until, findChrome, openPage } = require('./helpers');

const SECRET = 'correct-horse';
const latest = (client, kind) => client.texts().map(JSON.parse).filter(message => message.kind === kind).at(-1);
const cmd = (client, action, fields = {}) => client.ws.send(JSON.stringify({ kind: 'cmd', a: action, ...fields }));

async function body(response, status = 200) {
  const result = await response.json();
  assert.equal(response.status, status, JSON.stringify(result));
  return result;
}
async function judge(t, server, game) {
  const token = game.links.judge.split('#')[1];
  const client = await connect(t, server.url(token, 'judge', undefined, game.id));
  client.ws.send('{"kind":"hello"}');
  assert.ok(await until(() => latest(client, 'state')));
  return client;
}
async function overlay(t, server, game) {
  const token = game.links.overlay.split('#')[1];
  const client = await connect(t, server.url(token, 'screen', undefined, game.id));
  client.ws.send('{"kind":"hello","mode":"overlay"}');
  assert.ok(await until(() => latest(client, 'view')));
  return client;
}

test('две игры одновременно ведут свой протокол, таймер и оверлей', async t => {
  const server = await startServer(t, SECRET, undefined, undefined, false);
  assert.equal((await fetch(server.http + '/api/dashboard')).status, 401);
  const admin = await signIn(server.http, SECRET);
  const tournament = await testTournament(admin);
  const fixtures = await stageGames(admin, tournament.id, { rounds: 2 });
  const games = await Promise.all(fixtures.map(game => placeTestGame(admin, tournament.id, game.id, tournament.seating)));
  const [first, second] = await Promise.all(games.map(game => judge(t, server, game)));
  const [hud1, hud2] = await Promise.all(games.map(game => overlay(t, server, game)));
  assert.equal(await connect(t, server.url(games[0].links.judge.split('#')[1], 'judge', undefined, games[1].id)), 4403);
  assert.equal(await connect(t, server.url(games[0].links.overlay.split('#')[1], 'screen', undefined, games[1].id)), 4403);

  cmd(first, 'timer', { op: 'speak', v: '1', ms: 60000 });
  cmd(second, 'timer', { op: 'speak', v: '3', ms: 30000 });
  assert.ok(await until(() => latest(hud1, 'view').view.timer.speaker === '1' && latest(hud2, 'view').view.timer.speaker === '3'));
  cmd(first, 'role', { i: 0, v: 'don' });
  cmd(first, 'nom', { i: 0 });
  cmd(first, 'voteEnd');
  assert.ok(await until(() => latest(hud1, 'view').view.day === 2));
  assert.equal(latest(hud2, 'view').view.day, 1);
  assert.equal(latest(hud2, 'view').view.seats[0].role, '');
  assert.equal(latest(hud2, 'view').view.timer.speaker, '3');
  assert.equal((await fetch(server.http + '/api/public/games/' + games[0].id)).status, 404);

  await server.stop();
  const restored = await startServer(t, SECRET, server.data, undefined, false);
  const nextAdmin = await signIn(restored.http, SECRET);
  const saved = await Promise.all(games.map(async game => body(await nextAdmin('/games/' + game.id))));
  assert.equal(saved[0].day, 2);
  assert.deepEqual(saved[0].days[0].out, ['0']);
  assert.equal(saved[1].day, 1);
  assert.equal(saved[1].links.judge, games[1].links.judge);
});

