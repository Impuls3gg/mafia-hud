test('админка готовит игры по стадиям, рассаживает игроков и фиксирует места', async t => {
  const server = await startServer(t, SECRET, undefined, undefined, false);
  const admin = await signIn(server.http, SECRET);
  const tournament = await body(await admin('/tournaments', 'POST', { title: 'Кубок' }), 201);
  const path = '/tournaments/' + tournament.id;
  const act = (action, data = {}) => admin(path + '/admin/' + action, 'POST', data);
  const players = await body(await admin(path + '/participants', 'POST', {
    players: Array.from({ length: 20 }, (_, i) => ({ nick: 'Игрок ' + (i + 1), confirmed: i !== 0, paid: i === 0 })),
  }), 201);
  await body(await act('stage', { name: 'Отборы', rounds: 3, players: 20, coefficient: 1.25, final: false, swiss: true }));
  const setup = () => admin(path + '/admin').then(response => body(response));
  const [stage] = (await setup()).stages;
  await body(await act('judge', { nick: 'Первый судья', table: 1 }));
  const [official] = (await setup()).judges;
  await body(await act('pair', { player: players[0].id, judge: official.id, rule: 'together' }));
  assert.equal((await body(await act('create', { stageId: stage.id }))).created, 6);
  assert.equal((await body(await act('create', { stageId: stage.id }))).created, 0);
  assert.equal((await act('place', { stageId: stage.id })).status, 409);
  await body(await act('confirm'));
  const details = () => admin(path).then(response => body(response));
  const initial = await details();
  assert.equal(initial.roster.find(player => player.id === players[0].id).paid, true);
  const original = initial.games[0];
  const hud = await overlay(t, server, await body(await admin('/games/' + original.id)));
  assert.equal((await body(await act('place', { stageId: stage.id }))).placed, 2);
  assert.ok(await until(() => latest(hud, 'view').view.seats.every(seat => seat.pid)));
  const current = await details();
  const first = current.games.filter(game => game.stageRound === 1);
  assert.equal(new Set(first.flatMap(game => game.seats.map(seat => seat.nick))).size, 20);
  assert.equal(first[0].judgeName, official.nick);
  assert.ok(first[0].seats.some(seat => seat.nick === players[0].nick));
  assert.ok(current.games.slice(2).every(game => !game.seats.length));
  assert.deepEqual((await setup()).pairStats, [[1, 90]]);
  const closeGame = async game => {
    const judgeClient = await judge(t, server, await body(await admin('/games/' + game.id)));
    cmd(judgeClient, 'winner', { v: 'red' });
    assert.ok(await until(() => latest(judgeClient, 'state').winner === 'red'));
    return judgeClient;
  };
  const judgeClient = await closeGame(first[0]);
  assert.equal((await body(await act('place', { stageId: stage.id }))).placed, 0);
  await closeGame(first[1]);
  assert.equal((await body(await act('place', { stageId: stage.id }))).placed, 2);
  const importRows = players.slice(0, 10).map((player, i) => [1, 1, i + 1, player.nick]);
  const skipped = await body(await act('place', { stageId: stage.id, rows: importRows, overwrite: true }));
  assert.deepEqual(skipped, { placed: 0, skipped: 1 });
  const invalid = [...importRows.slice(0, 9), [1, 1, 10, 'Неучастник']];
  assert.equal((await act('place', { stageId: stage.id, rows: invalid, overwrite: true })).status, 400);
  const third = players.map((player, i) => [3, i < 10 ? 1 : 2, i % 10 + 1, player.nick]);
  assert.equal((await body(await act('place', { stageId: stage.id, rows: third }))).placed, 2);
  assert.deepEqual((await details()).games.at(-1).seats.map(seat => seat.nick), players.slice(10).map(player => player.nick));
  assert.equal((await act('finalize')).status, 409);
  const removed = await body(await act('remove-unfinished'));
  assert.equal(removed.removed, 4);
  await body(await act('stage', { ...stage, rounds: 1 }));
  const preliminary = (await body(await act('calculate'))).standings;
  assert.equal(preliminary[0].points, 1.25);
  const finished = await body(await act('finalize'));
  assert.equal(finished.standings[0].place, 1);
  assert.ok((await details()).finalizedAt);
  assert.equal((await act('create', { stageId: stage.id })).status, 409);
  cmd(judgeClient, 'winner', { v: 'draw' });
  assert.ok(await until(() => latest(judgeClient, 'state').winner === 'draw'));
  assert.deepEqual((await details()).standings, finished.standings);
  await body(await act('reopen'));
  assert.equal((await details()).finalizedAt, null);
  assert.ok((await details()).standings.some(row => row.points === 0));
});

